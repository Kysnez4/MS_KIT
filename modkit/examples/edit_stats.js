// ШАБЛОН: меняет характеристики артефактов и комбинаций без пересборки.
// Положите файл в Download/ModKit/ (или Android/data/com.vkslrzm.Zombie/files/modkit/mods/),
// отредактируйте список EDITS ниже и нажмите «+» в окне «Моды» (или перезапустите игру).
//
// Каждая запись: таблица, ID строки и что менять. Названия колонок — modkit/docs/TABLES.md,
// ID эффектов — modkit/docs/EFFECTS.md. Эффект = пара «ID эффекта» (효과ID_NN) и «значение» (효과ID_NN값).
// Текст в описании (효과 설명줄NN) править вручную — иначе игрок увидит старое число.
const EDITS = [
    // Артефакт «Сюрикен» (Ability 210): шанс крита магической пули +15% -> +50%.
    // У него два эффекта (170 и 287, оба 15) — какой из них что делает, не проверено, поэтому меняем оба.
    { table: "Ability", id: 210, set: { "효과ID_01값": 50, "효과ID_02값": 50, "효과 설명줄01": "Шанс критического удара магической пули +50%" } },
    // Комбинация «Аватар» (MagicCom 33): множитель урона пуль ×9,99 (эффект 851, значение 999) -> ×20
    { table: "MagicCom", id: 33, set: { "효과ID_06값": 2000, "효과 설명줄04": "Урон магических пуль х20" } },
];

ModKit.define({
    id: "ext_edit_stats",
    name: "Правка артефактов и комбинаций",
    description: "Список правок — в начале файла edit_stats.js.",
    onEnable(ctx) {
        ctx.data.whenReady(() => {
            for (const e of EDITS) {
                try {
                    ctx.data.edit(e.table, e.id, e.set);
                    ctx.log(`правка ${e.table} #${e.id}: ${JSON.stringify(e.set)}`);
                } catch (err) {
                    ctx.log(`правка ${e.table} #${e.id} не удалась: ${err}`);
                }
            }
        });
    },
});
