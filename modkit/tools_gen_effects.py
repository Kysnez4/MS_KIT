covered = set()
for block in DESC.strip("\n").split("\n"):
    if not block.strip(): continue
    if block.startswith("# "):
        out += ["", "## " + block[2:], "", "| ID | ув. | значение | что делает | на что влияет | где (кол-во, пример) |", "|---|---|---|---|---|---|"]
        continue
    spec, conf, val, what, aff = block.split("|")
    ids = sorted({e for e in uses if is_known(spec, e)})
    if spec in ("-N (1…21)", "-30…-39", "-306, -307, -316"):
        lst = [u for e in ids for u in uses[e]]
        covered.update(ids)
        ex = f"{len(lst)}; напр. {lst[0][0]} #{lst[0][1]} {lst[0][2]}" if lst else "—"
        out.append(f"| {spec} | {conf} | {val} | {what} | {aff} | {ex} |")
        continue
    eid = int(spec)
    covered.add(eid)
    u = uses.get(eid, [])
