    ex = f"{len(u)}; напр. {u[0][0]} #{u[0][1]} {u[0][2]} (знач. {u[0][3]})" if u else "нет в таблицах"
    out.append(f"| {eid} | {conf} | {val} | {what} | {aff} | {ex} |")

